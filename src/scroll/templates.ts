// The Scroll library: every spot a card can be. A template says where you sit, how deep, which bots could be
// across the table, what kind of hand and board you're dealt, the moves played before you take over, and the goal.
// A seed turns it into one deal (see deal.ts), so the same template gives a different hand every time.
//
// Writing for the intro popups: short, plain, contractions fine, and honest about the bot (cards name the style).

import type { Goal, Step, Template, Want } from './types';

// ── Moves to script ─────────────────────────────────────────────────────────

const mk = (by: 'you' | 'bot') => ({
  fold: (): Step => ({ by, do: 'fold' }),
  check: (): Step => ({ by, do: 'check' }),
  call: (): Step => ({ by, do: 'call' }),
  allin: (): Step => ({ by, do: 'allin' }),
  /** Raise (or bet) to this many big blinds on the street. */
  to: (to: number): Step => ({ by, do: 'raise', to }),
  /** A bet of this share of the pot. */
  bet: (pot: number): Step => ({ by, do: 'bet', pot }),
  /** A raise to this multiple of the bet in front. */
  x: (x: number): Step => ({ by, do: 'raise', x }),
});
const y = mk('you');
const b = mk('bot');

const preflop = (strength: [number, number]): Want => ({ street: 'preflop', strength });
const on = (
  street: 'flop' | 'turn' | 'river',
  bucket: NonNullable<Want['bucket']>,
  texture?: Want['texture'],
  strength?: [number, number],
): Want => ({ street, bucket, texture, strength });

